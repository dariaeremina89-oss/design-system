import {test,expect} from '@playwright/test';
const story = (name:string) => `/iframe.html?id=components-navigation-carousel--${name}&viewMode=story`;
test('geometry, keyboard, overflow and reduced motion', async ({page}) => {
  await page.goto(story('many-items'));
  const carousel=page.getByTestId('carousel');
  await expect(carousel).toBeVisible();
  const dot=carousel.locator('[aria-current="true"]');
  await expect(dot).toHaveCSS('width','16px');
  await expect(dot).toHaveCSS('height','8px');
  await expect(carousel.locator('.fdoc-carousel__arrow').first()).toHaveCSS('width','32px');
  await carousel.getByRole('button',{name:'Перейти к элементу 1 из 16',exact:true}).focus();
  await page.keyboard.press('End');
  await expect(carousel.getByRole('button',{name:'Перейти к элементу 16 из 16',exact:true})).toBeFocused();
  await expect(dot).toHaveAttribute('aria-label','Перейти к элементу 1 из 16');
  await page.keyboard.press('Enter');
  await expect(carousel.getByRole('button',{name:'Следующий элемент',exact:true})).toBeDisabled();
  await expect.poll(()=>carousel.locator('.fdoc-carousel__indicators').evaluate(el=>el.scrollLeft)).toBeGreaterThan(0);
  await page.emulateMedia({reducedMotion:'reduce'});
  await expect(dot).toHaveCSS('transition-duration','0s');
  await page.goto(story('narrow'));
  await expect(carousel).toBeVisible();
  expect((await carousel.boundingBox())!.width).toBeLessThanOrEqual(160);
});
test('drag follows pointer, commits, snaps back and handles rapid navigation', async ({page}) => {
  await page.goto(story('first-element'));
  const viewport=page.locator('.fdoc-carousel-viewport'), track=page.locator('.fdoc-carousel-viewport__track');
  await expect(viewport).toBeVisible();
  const box=(await viewport.boundingBox())!;
  const x=box.x+box.width*.75,y=box.y+80;
  await page.mouse.move(x,y); await page.mouse.down(); await page.mouse.move(x-160,y,{steps:8});
  await expect(track).toHaveAttribute('data-dragging','true');
  await page.mouse.up();
  await expect(page.locator('[aria-current="true"]')).toHaveAttribute('aria-label','Перейти к элементу 2 из 6');
  await page.waitForTimeout(250);
  await page.mouse.move(x,y); await page.mouse.down(); await page.mouse.move(x-10,y,{steps:5}); await page.waitForTimeout(150); await page.mouse.up();
  await expect(page.locator('[aria-current="true"]')).toHaveAttribute('aria-label','Перейти к элементу 2 из 6');
  await page.getByRole('button',{name:'Следующий элемент',exact:true}).click({clickCount:3});
  await expect(page.locator('[aria-current="true"]')).toHaveAttribute('aria-label','Перейти к элементу 5 из 6');
  await expect(track).toHaveCSS('transform','matrix(1, 0, 0, 1, -1920, 0)');
});
test('touch swipe changes slide without trapping vertical scrolling', async ({browser})=>{
  const context=await browser.newContext({viewport:{width:375,height:700},hasTouch:true,isMobile:true});
  const page=await context.newPage(); await page.goto(`http://127.0.0.1:6006${story('first-element')}`);
  const viewport=page.locator('.fdoc-carousel-viewport'); await expect(viewport).toBeVisible();
  await expect(viewport).toHaveCSS('touch-action','pan-y');
  const b=(await viewport.boundingBox())!, cdp=await context.newCDPSession(page);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:b.x+250,y:b.y+80}]});
  for(let i=1;i<=6;i++) await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:b.x+250-i*25,y:b.y+80}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await expect(page.locator('[aria-current="true"]')).toHaveAttribute('aria-label','Перейти к элементу 2 из 6');
  await context.close();
});
