function cleanMarkdown(value: string) {
  return value
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();
}

export function resolveStoryCheckDescription(
  storyName: string,
  explicit?: unknown,
  docsDescription?: unknown,
) {
  if (typeof explicit === 'string' && explicit.trim()) return cleanMarkdown(explicit);
  if (typeof docsDescription === 'string' && docsDescription.trim()) {
    return cleanMarkdown(docsDescription);
  }

  const normalized = storyName
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLocaleLowerCase();

  if (exactStoryChecks[normalized]) return exactStoryChecks[normalized];

  if (normalized.includes('skeleton')) return 'Skeleton-состояние: состав заглушек, размеры и отсутствие скачка геометрии.';
  if (normalized.includes('disabled')) return 'Disabled-состояние и блокировка недоступных действий.';
  if (normalized.includes('error')) return 'Ошибка в этом сценарии: текст, семантический цвет и влияние на геометрию.';
  if (normalized.includes('focused') || normalized.includes('focus')) return 'Фокус, focus-стили и сохранение корректной геометрии.';
  if (normalized.includes('loading')) return 'Состояние загрузки и стабильность компонента во время ожидания.';
  if (normalized.includes('mobile')) return 'Мобильное состояние: ширина, переносы, типографика и отсутствие overflow.';
  if (normalized.includes('long')) return 'Длинный контент: переносы и сохранение границ компонента.';
  if (normalized.includes('with icons') || normalized.includes('icon')) return 'Работа иконок, их размер, позиция и выравнивание с контентом.';
  if (normalized.includes('selected')) return 'Выбранное состояние и его отображение в основном контроле и связанных элементах.';
  if (normalized.includes('horizontal')) return 'Горизонтальная компоновка элементов и корректность отступов.';
  if (normalized.includes('vertical')) return 'Вертикальная компоновка и корректность размеров и отступов.';
  if (normalized.includes('state')) return 'Состояния компонента и различия их визуального и интерактивного поведения.';
  if (normalized.includes('size')) return 'Размеры компонента и соответствие внутренних элементов выбранному size.';
  if (normalized.includes('color') || normalized.includes('background')) return 'Цветовые варианты и использование семантических токенов.';
  if (normalized.includes('validation')) return 'Валидация и отображение обратной связи пользователю.';
  if (normalized.includes('menu') || normalized.includes('dropdown')) return 'Открытое Menu и взаимодействие с его содержимым.';
  if (normalized.includes('search')) return 'Поисковый сценарий, ввод запроса и отображение результата.';
  if (normalized.includes('selection')) return 'Выбор значения и его визуальное/доступное состояние.';
  if (normalized.includes('responsive') || normalized.includes('adaptive') || normalized.includes('narrow')) return 'Адаптивное поведение при изменении доступной ширины.';
  if (normalized.includes('overflow') || normalized.includes('edge')) return 'Поведение у границ контейнера и при переполнении.';
  if (normalized.includes('filled')) return 'Заполненное состояние и отображение введенного или выбранного значения.';
  if (normalized.includes('empty')) return 'Пустое состояние и сообщение при отсутствии содержимого.';
  if (normalized.includes('control')) return 'Управляемое взаимодействие и синхронизация внешнего значения с компонентом.';

  return 'Визуальное состояние, состав и поведение компонента в этом сценарии.';
}
